CREATE TABLE IF NOT EXISTS public.history_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano INTEGER NOT NULL,
    mes TEXT NOT NULL,
    fecha TEXT NOT NULL,
    tipo_doc TEXT NOT NULL,
    numero INTEGER NOT NULL,
    id_cliente INTEGER NOT NULL,
    cliente TEXT NOT NULL,
    id_vendedor INTEGER NOT NULL,
    vendedor TEXT NOT NULL,
    id_articulo INTEGER NOT NULL,
    articulo TEXT NOT NULL,
    cajas NUMERIC(14, 2) NOT NULL DEFAULT 0,
    unidades NUMERIC(14, 2) NOT NULL DEFAULT 0,
    kgs_lts NUMERIC(14, 2) NOT NULL DEFAULT 0,
    monto NUMERIC(14, 2) NOT NULL DEFAULT 0,
    costo NUMERIC(14, 2) NOT NULL DEFAULT 0,
    utilidad NUMERIC(14, 2) NOT NULL DEFAULT 0,
    porcentaje_utilidad NUMERIC(10, 4) NOT NULL DEFAULT 0,
    numero_fila INTEGER,
    composite_row_key TEXT
);

