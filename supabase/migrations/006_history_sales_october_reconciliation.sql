-- 5. Función RPC de Agregación Exacta en Servidor (100% de filas sin límite de 1,000 de PostgREST)
-- Usa parámetros TEXT y cast explícito `fecha::text` para evitar ERROR 42883 (text >= date)
DROP FUNCTION IF EXISTS public.fn_resumen_mensual_history_sales(DATE, DATE);
DROP FUNCTION IF EXISTS public.fn_resumen_mensual_history_sales(TEXT, TEXT);

CREATE OR REPLACE FUNCTION public.fn_resumen_mensual_history_sales(
    p_fecha_inicio TEXT DEFAULT '2026-10-01',
    p_fecha_fin TEXT DEFAULT '2026-10-31'
)
RETURNS TABLE (
    total_registros BIGINT,
    registros_fa BIGINT,
    registros_dv BIGINT,
    monto_neto NUMERIC,
    monto_fa NUMERIC,
    monto_dv NUMERIC,
    costo_neto NUMERIC,
    costo_fa NUMERIC,
    costo_dv NUMERIC,
    utilidad_neta NUMERIC,
    utilidad_fa NUMERIC,
    utilidad_dv NUMERIC,
    kgs_neto NUMERIC,
    kgs_fa NUMERIC,
    kgs_dv NUMERIC,
    kgs_bruto_absoluto NUMERIC,
    unidades_neto NUMERIC,
    unidades_fa NUMERIC,
    unidades_dv NUMERIC,
    cajas_neto NUMERIC,
    cajas_fa NUMERIC,
    cajas_dv NUMERIC
)
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
    SELECT
        COUNT(*)::BIGINT AS total_registros,
        COUNT(*) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'FA')::BIGINT AS registros_fa,
        COUNT(*) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'DV')::BIGINT AS registros_dv,
        ROUND(COALESCE(SUM(monto), 0)::NUMERIC, 2) AS monto_neto,
        ROUND(COALESCE(SUM(monto) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'FA'), 0)::NUMERIC, 2) AS monto_fa,
        ROUND(COALESCE(SUM(monto) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'DV'), 0)::NUMERIC, 2) AS monto_dv,
        ROUND(COALESCE(SUM(costo), 0)::NUMERIC, 2) AS costo_neto,
        ROUND(COALESCE(SUM(costo) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'FA'), 0)::NUMERIC, 2) AS costo_fa,
        ROUND(COALESCE(SUM(costo) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'DV'), 0)::NUMERIC, 2) AS costo_dv,
        ROUND(COALESCE(SUM(utilidad), 0)::NUMERIC, 2) AS utilidad_neta,
        ROUND(COALESCE(SUM(utilidad) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'FA'), 0)::NUMERIC, 2) AS utilidad_fa,
        ROUND(COALESCE(SUM(utilidad) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'DV'), 0)::NUMERIC, 2) AS utilidad_dv,
        ROUND(COALESCE(SUM(kgs_lts), 0)::NUMERIC, 2) AS kgs_neto,
        ROUND(COALESCE(SUM(kgs_lts) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'FA'), 0)::NUMERIC, 2) AS kgs_fa,
        ROUND(COALESCE(SUM(kgs_lts) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'DV'), 0)::NUMERIC, 2) AS kgs_dv,
        ROUND(COALESCE(SUM(ABS(kgs_lts)), 0)::NUMERIC, 2) AS kgs_bruto_absoluto,
        ROUND(COALESCE(SUM(unidades), 0)::NUMERIC, 2) AS unidades_neto,
        ROUND(COALESCE(SUM(unidades) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'FA'), 0)::NUMERIC, 2) AS unidades_fa,
        ROUND(COALESCE(SUM(unidades) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'DV'), 0)::NUMERIC, 2) AS unidades_dv,
        ROUND(COALESCE(SUM(cajas), 0)::NUMERIC, 2) AS cajas_neto,
        ROUND(COALESCE(SUM(cajas) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'FA'), 0)::NUMERIC, 2) AS cajas_fa,
        ROUND(COALESCE(SUM(cajas) FILTER (WHERE UPPER(TRIM(tipo_doc::text)) = 'DV'), 0)::NUMERIC, 2) AS cajas_dv
    FROM public.history_sales
    WHERE fecha::text >= p_fecha_inicio::text
      AND fecha::text <= p_fecha_fin::text;
$$;

GRANT EXECUTE ON FUNCTION public.fn_resumen_mensual_history_sales(TEXT, TEXT) TO anon, authenticated, service_role;
