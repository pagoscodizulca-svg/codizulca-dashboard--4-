ALTER TABLE public.history_sales ADD COLUMN IF NOT EXISTS utilidad NUMERIC(14, 2) NOT NULL DEFAULT 0;
ALTER TABLE public.history_sales ADD COLUMN IF NOT EXISTS porcentaje_utilidad NUMERIC(10, 4) NOT NULL DEFAULT 0;
ALTER TABLE public.history_sales ADD COLUMN IF NOT EXISTS numero_fila INTEGER;
ALTER TABLE public.history_sales ADD COLUMN IF NOT EXISTS composite_row_key TEXT;

-- 2. Eliminar cualquier restricción UNIQUE errónea sobre `numero` individual
-- (En Octubre 2026 existen 13,588 números de documento únicos distribuidos en 29,722 filas)
ALTER TABLE public.history_sales DROP CONSTRAINT IF EXISTS history_sales_numero_key;
ALTER TABLE public.history_sales DROP CONSTRAINT IF EXISTS uq_history_sales_numero;

-- 3. Crear índice único parcial sobre composite_row_key (sin afectar filas históricas con NULL)
DROP INDEX IF EXISTS public.uq_history_sales_composite_row_key;
CREATE UNIQUE INDEX IF NOT EXISTS uq_history_sales_composite_row_key
ON public.history_sales (composite_row_key)
WHERE composite_row_key IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_history_sales_fecha ON public.history_sales (fecha);
CREATE INDEX IF NOT EXISTS idx_history_sales_ano_mes ON public.history_sales (ano, mes);

